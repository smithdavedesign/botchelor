/**
 * The machine-readable "AI-generated" mark (EU AI Act Art. 50(2), due 2026-12-02 for systems already on the market;
 * docs/after-dark-legal-review.md "Other laws"; docs/after-dark.md "AI marking, crisis notice and profile consent").
 *
 * Every picture the site makes (venue sets, look tiles, portraits, season portraits, After Dark pictures, beats and
 * keyframes, share cards with a portrait in them) carries an XMP packet that says so in IPTC's vocabulary:
 * `Iptc4xmpExt:DigitalSourceType = trainedAlgorithmicMedia`, plus a short description and credit naming Botchelor.
 * Written in place, without decoding or re-encoding the picture (so no quality is lost, and no native library is
 * needed where it runs): an APP1 segment in a JPEG, an iTXt chunk in a PNG, an "XMP " chunk in a WebP (a simple WebP
 * becomes an extended one, as the format asks). Any other bytes come back untouched, and so do bytes that already
 * carry this mark, so stamping twice (on store and again on serve) is a no-op. It never throws: a picture it can't
 * parse is served as it was.
 *
 * An MP4 gets the same packet in a top-level `uuid` box (Adobe's XMP box for ISO base media files), appended at its end
 * so nothing else in the file moves (markAiVideo, 2026-10-26: the creator suite's exports, and every video kept). Audio
 * isn't stamped: its routes send `X-AI-Generated: true` and a Link to the content policy instead (AI_HEADERS), as every
 * file's do. Full C2PA signing is out of scope: it needs a signing certificate. A provider's own C2PA manifest (OpenAI's,
 * in a JPEG's APP11 or a PNG's caBX) is kept.
 */

export const DIGITAL_SOURCE_TYPE = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia";
export const AI_CREDIT = "AI-generated by Botchelor";
export const AI_DESCRIPTION = "AI-generated by Botchelor (botchelor.com). Fictional: no real person is depicted.";
/** Where the headers point: the site's content policy (the legal pages' /content-policy). */
export const AI_POLICY_PATH = "/content-policy";

/** The headers every AI-generated file is served with (pictures too, so a client that ignores XMP still knows). */
export const AI_HEADERS: Readonly<Record<string, string>> = {
  "x-ai-generated": "true",
  link: `<${AI_POLICY_PATH}>; rel="describedby"`,
};

/** The XMP packet: one Description, attributes only where the value is a plain string (what most readers expect). */
export const AI_XMP = [
  '<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>',
  '<x:xmpmeta xmlns:x="adobe:ns:meta/">',
  '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">',
  '<rdf:Description rdf:about=""',
  ' xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"',
  ' xmlns:dc="http://purl.org/dc/elements/1.1/"',
  ' xmlns:photoshop="http://ns.adobe.com/photoshop/1.0/"',
  ' xmlns:xmp="http://ns.adobe.com/xap/1.0/"',
  ` Iptc4xmpExt:DigitalSourceType="${DIGITAL_SOURCE_TYPE}"`,
  ` photoshop:Credit="${AI_CREDIT}"`,
  ' xmp:CreatorTool="Botchelor">',
  `<dc:description><rdf:Alt><rdf:li xml:lang="x-default">${AI_DESCRIPTION}</rdf:li></rdf:Alt></dc:description>`,
  `<dc:creator><rdf:Seq><rdf:li>${AI_CREDIT}</rdf:li></rdf:Seq></dc:creator>`,
  "</rdf:Description>",
  "</rdf:RDF>",
  "</x:xmpmeta>",
  '<?xpacket end="w"?>',
].join("\n");

const XMP_BYTES = Buffer.from(AI_XMP, "utf8");
const MARKER = Buffer.from(AI_CREDIT, "utf8");
const JPEG_XMP_NS = Buffer.from("http://ns.adobe.com/xap/1.0/\0", "latin1");
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const PNG_XMP_KEYWORD = "XML:com.adobe.xmp";

export type ImageKind = "jpeg" | "png" | "webp";

/** What a file is, by its first bytes (never by the type it was labelled with). */
export function imageKind(b: Uint8Array): ImageKind | null {
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "jpeg";
  if (b.length >= 8 && Buffer.from(b.subarray(0, 8)).equals(PNG_SIGNATURE)) return "png";
  if (b.length >= 12 && Buffer.from(b.subarray(0, 4)).toString("latin1") === "RIFF" && Buffer.from(b.subarray(8, 12)).toString("latin1") === "WEBP") return "webp";
  return null;
}

/** Whether these bytes already carry the mark (ours: a provider's own XMP doesn't count). */
export const hasAiMark = (b: Uint8Array): boolean => Buffer.from(b.buffer, b.byteOffset, b.byteLength).indexOf(MARKER) !== -1;

/**
 * The picture with the mark written into it, or the same bytes when it already has it, isn't a JPEG, PNG or WebP, or
 * can't be parsed. Never throws.
 */
export function markAiImage(input: Buffer | Uint8Array): Buffer {
  const bytes = Buffer.isBuffer(input) ? input : Buffer.from(input.buffer, input.byteOffset, input.byteLength);
  try {
    if (hasAiMark(bytes)) return bytes;
    const kind = imageKind(bytes);
    const out = kind === "jpeg" ? markJpeg(bytes) : kind === "png" ? markPng(bytes) : kind === "webp" ? markWebp(bytes) : null;
    return out ?? bytes;
  } catch {
    return bytes;
  }
}

/** A `data:image/…;base64,` URL with the mark written into its picture (anything else back as it was). */
export function markAiDataUrl(url: string): string {
  const m = /^data:(image\/(?:png|jpeg|webp));base64,/.exec(url);
  if (!m) return url;
  const bytes = Buffer.from(url.slice(m[0].length), "base64");
  const marked = markAiImage(bytes);
  return marked === bytes ? url : `${m[0]}${marked.toString("base64")}`;
}

/** The XMP packet a picture carries, as text (JPEG APP1, PNG iTXt, WebP "XMP "), or null. For tests and checks. */
export function readXmp(input: Buffer | Uint8Array): string | null {
  const b = Buffer.isBuffer(input) ? input : Buffer.from(input);
  try {
    const kind = imageKind(b);
    if (kind === "jpeg") {
      for (const s of jpegSegments(b) ?? []) {
        if (s.marker === 0xe1 && b.subarray(s.start + 4, s.start + 4 + JPEG_XMP_NS.length).equals(JPEG_XMP_NS)) {
          return b.subarray(s.start + 4 + JPEG_XMP_NS.length, s.end).toString("utf8");
        }
      }
    } else if (kind === "png") {
      for (const c of pngChunks(b) ?? []) {
        if (c.type !== "iTXt") continue;
        const data = b.subarray(c.dataStart, c.dataEnd);
        const nul = data.indexOf(0);
        if (data.subarray(0, nul).toString("latin1") !== PNG_XMP_KEYWORD) continue;
        // keyword\0 compression(1) method(1) language\0 translated\0 text
        let p = nul + 3;
        p = data.indexOf(0, p) + 1;
        p = data.indexOf(0, p) + 1;
        return data.subarray(p).toString("utf8");
      }
    } else if (kind === "webp") {
      for (const c of webpChunks(b) ?? []) if (c.fourcc === "XMP ") return b.subarray(c.dataStart, c.dataStart + c.size).toString("utf8");
    }
  } catch {
    /* unreadable: no packet */
  }
  return null;
}

// ---------------------------------------------------------------------------------------------------------------------
// JPEG: an APP1 segment, "http://ns.adobe.com/xap/1.0/\0" then the packet, after the JFIF/Exif segments.
// ---------------------------------------------------------------------------------------------------------------------

type Segment = { marker: number; start: number; end: number };

/** The segments between SOI and the first scan (SOS), or null when the file isn't laid out as a JPEG should be. */
function jpegSegments(b: Buffer): Segment[] | null {
  const out: Segment[] = [];
  let p = 2;
  while (p + 4 <= b.length) {
    if (b[p] !== 0xff) return null;
    const marker = b[p + 1];
    if (marker === 0xff) {
      p++; // fill byte
      continue;
    }
    if (marker === 0xda || marker === 0xd9) return out; // start of scan, or end of image
    if (marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
      p += 2;
      continue;
    }
    const len = b.readUInt16BE(p + 2);
    if (len < 2 || p + 2 + len > b.length) return null;
    out.push({ marker, start: p, end: p + 2 + len });
    p += 2 + len;
  }
  return null;
}

function markJpeg(b: Buffer): Buffer | null {
  const segs = jpegSegments(b);
  if (!segs) return null;
  const payload = Buffer.concat([JPEG_XMP_NS, XMP_BYTES]);
  if (payload.length + 2 > 0xffff) return null;
  const app1 = Buffer.alloc(4);
  app1[0] = 0xff;
  app1[1] = 0xe1;
  app1.writeUInt16BE(payload.length + 2, 2);
  const isXmp = (s: Segment) => s.marker === 0xe1 && b.subarray(s.start + 4, s.start + 4 + JPEG_XMP_NS.length).equals(JPEG_XMP_NS);
  // After the leading JFIF (APP0) and Exif (APP1) segments, where readers look for it; any older XMP packet goes.
  let at = 2;
  for (const s of segs) {
    if (s.marker === 0xe0 || (s.marker === 0xe1 && !isXmp(s))) at = s.end;
    else break;
  }
  const parts: Buffer[] = [b.subarray(0, at), app1, payload];
  let p = at;
  for (const s of segs) {
    if (s.start < at || !isXmp(s)) continue;
    parts.push(b.subarray(p, s.start));
    p = s.end;
  }
  parts.push(b.subarray(p));
  return Buffer.concat(parts);
}

// ---------------------------------------------------------------------------------------------------------------------
// PNG: an iTXt chunk keyed "XML:com.adobe.xmp" (uncompressed), right after IHDR.
// ---------------------------------------------------------------------------------------------------------------------

type Chunk = { type: string; start: number; dataStart: number; dataEnd: number; end: number };

function pngChunks(b: Buffer): Chunk[] | null {
  const out: Chunk[] = [];
  let p = 8;
  while (p + 12 <= b.length) {
    const len = b.readUInt32BE(p);
    const type = b.subarray(p + 4, p + 8).toString("latin1");
    const end = p + 12 + len;
    if (end > b.length) return null;
    out.push({ type, start: p, dataStart: p + 8, dataEnd: p + 8 + len, end });
    p = end;
    if (type === "IEND") return out;
  }
  return null;
}

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(...parts: Buffer[]): number {
  let c = 0xffffffff;
  for (const part of parts) for (let i = 0; i < part.length; i++) c = CRC_TABLE[(c ^ part[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function markPng(b: Buffer): Buffer | null {
  const chunks = pngChunks(b);
  if (!chunks || chunks[0]?.type !== "IHDR") return null;
  const type = Buffer.from("iTXt", "latin1");
  // keyword \0, compression flag 0, method 0, language "" \0, translated keyword "" \0, then the text.
  const data = Buffer.concat([Buffer.from(PNG_XMP_KEYWORD, "latin1"), Buffer.from([0, 0, 0, 0, 0]), XMP_BYTES]);
  const head = Buffer.alloc(4);
  head.writeUInt32BE(data.length);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(type, data));
  const isXmp = (c: Chunk) => c.type === "iTXt" && b.subarray(c.dataStart, c.dataStart + PNG_XMP_KEYWORD.length + 1).equals(Buffer.from(`${PNG_XMP_KEYWORD}\0`, "latin1"));
  const parts: Buffer[] = [b.subarray(0, chunks[0].end), head, type, data, crc];
  let p = chunks[0].end;
  for (const c of chunks.slice(1)) {
    if (!isXmp(c)) continue;
    parts.push(b.subarray(p, c.start));
    p = c.end;
  }
  parts.push(b.subarray(p));
  return Buffer.concat(parts);
}

// ---------------------------------------------------------------------------------------------------------------------
// WebP: an "XMP " chunk at the end, with VP8X's XMP flag set (a simple VP8 / VP8L file gets a VP8X header first).
// ---------------------------------------------------------------------------------------------------------------------

type RiffChunk = { fourcc: string; start: number; dataStart: number; size: number; end: number };

function webpChunks(b: Buffer): RiffChunk[] | null {
  const out: RiffChunk[] = [];
  const riffEnd = Math.min(b.length, 8 + b.readUInt32LE(4));
  let p = 12;
  while (p + 8 <= riffEnd) {
    const fourcc = b.subarray(p, p + 4).toString("latin1");
    const size = b.readUInt32LE(p + 4);
    const end = p + 8 + size + (size & 1);
    if (p + 8 + size > riffEnd) return null;
    out.push({ fourcc, start: p, dataStart: p + 8, size, end: Math.min(end, riffEnd) });
    p = end;
  }
  return out;
}

const XMP_FLAG = 0x04;
const ALPHA_FLAG = 0x10;

/** The canvas size (and whether it has alpha) of a simple WebP's one frame, or null. */
function simpleCanvas(b: Buffer, c: RiffChunk): { w: number; h: number; alpha: boolean } | null {
  const d = c.dataStart;
  if (c.fourcc === "VP8 " && c.size >= 10 && b[d + 3] === 0x9d && b[d + 4] === 0x01 && b[d + 5] === 0x2a) {
    return { w: b.readUInt16LE(d + 6) & 0x3fff, h: b.readUInt16LE(d + 8) & 0x3fff, alpha: false };
  }
  if (c.fourcc === "VP8L" && c.size >= 5 && b[d] === 0x2f) {
    const bits = b.readUInt32LE(d + 1);
    return { w: (bits & 0x3fff) + 1, h: ((bits >>> 14) & 0x3fff) + 1, alpha: Boolean((bits >>> 28) & 1) };
  }
  return null;
}

function chunk(fourcc: string, data: Buffer): Buffer {
  const head = Buffer.alloc(8);
  head.write(fourcc, 0, "latin1");
  head.writeUInt32LE(data.length, 4);
  return Buffer.concat([head, data, data.length & 1 ? Buffer.from([0]) : Buffer.alloc(0)]);
}

function markWebp(b: Buffer): Buffer | null {
  const chunks = webpChunks(b);
  if (!chunks?.length) return null;
  const kept: Buffer[] = chunks.filter((c) => c.fourcc !== "XMP ").map((c) => Buffer.from(b.subarray(c.start, c.end)));
  if (chunks[0].fourcc === "VP8X") {
    const vp8x = kept[0];
    vp8x[8] |= XMP_FLAG;
  } else {
    const canvas = simpleCanvas(b, chunks[0]);
    if (!canvas || chunks.length !== 1) return null;
    const data = Buffer.alloc(10);
    data[0] = XMP_FLAG | (canvas.alpha ? ALPHA_FLAG : 0);
    data.writeUIntLE(canvas.w - 1, 4, 3);
    data.writeUIntLE(canvas.h - 1, 7, 3);
    kept.unshift(chunk("VP8X", data));
  }
  const body = Buffer.concat([Buffer.from("WEBP", "latin1"), ...kept, chunk("XMP ", XMP_BYTES)]);
  const head = Buffer.alloc(8);
  head.write("RIFF", 0, "latin1");
  head.writeUInt32LE(body.length, 4);
  return Buffer.concat([head, body]);
}

// ---------------------------------------------------------------------------------------------------------------------
// Video: an MP4's top-level XMP box
// ---------------------------------------------------------------------------------------------------------------------

/** Adobe's id for the XMP box of an ISO base media file (MP4, MOV): a top-level `uuid` box with it holds the packet. */
const MP4_XMP_UUID = Buffer.from("be7acfcb97a942e89c71999491e3afac", "hex");
/** Whether these bytes are an ISO base media file: its first box is `ftyp`. */
const isMp4 = (b: Buffer) => b.length >= 12 && b.subarray(4, 8).toString("latin1") === "ftyp";

/** Each top-level box of an MP4: where it starts, its type, and where it ends. Null when the file doesn't parse. */
function mp4Boxes(b: Buffer): { start: number; type: string; body: number; end: number }[] | null {
  const boxes: { start: number; type: string; body: number; end: number }[] = [];
  let at = 0;
  while (at + 8 <= b.length) {
    let size = b.readUInt32BE(at);
    let body = at + 8;
    if (size === 1) {
      if (at + 16 > b.length) return null;
      size = Number(b.readBigUInt64BE(at + 8));
      body = at + 16;
    } else if (size === 0) size = b.length - at;
    if (size < body - at || at + size > b.length) return null;
    boxes.push({ start: at, type: b.subarray(at + 4, at + 8).toString("latin1"), body, end: at + size });
    at += size;
  }
  return at === b.length ? boxes : null;
}

/**
 * The MP4 with the XMP packet in a top-level `uuid` box at its end, or the same bytes when it already has one, isn't an
 * MP4, or doesn't parse. Never throws.
 */
export function markAiVideo(input: Buffer | Uint8Array): Buffer {
  const bytes = Buffer.isBuffer(input) ? input : Buffer.from(input.buffer, input.byteOffset, input.byteLength);
  try {
    if (!isMp4(bytes) || readMp4Xmp(bytes) !== null) return bytes;
    if (!mp4Boxes(bytes)) return bytes;
    const head = Buffer.alloc(8);
    head.writeUInt32BE(8 + MP4_XMP_UUID.length + XMP_BYTES.length, 0);
    head.write("uuid", 4, "latin1");
    return Buffer.concat([bytes, head, MP4_XMP_UUID, XMP_BYTES]);
  } catch {
    return bytes;
  }
}

/** The XMP packet in an MP4's top-level uuid box, as text, or null. For tests and checks. */
export function readMp4Xmp(input: Buffer | Uint8Array): string | null {
  const b = Buffer.isBuffer(input) ? input : Buffer.from(input);
  try {
    if (!isMp4(b)) return null;
    for (const box of mp4Boxes(b) ?? []) {
      if (box.type === "uuid" && b.subarray(box.body, box.body + 16).equals(MP4_XMP_UUID)) return b.subarray(box.body + 16, box.end).toString("utf8");
    }
    return null;
  } catch {
    return null;
  }
}

