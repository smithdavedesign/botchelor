/** A generated file's bytes as a route sends them: a picture marked (a video or a voice as it is: AI_HEADERS mark it). */
export const aiBody = (bytes: Buffer | Uint8Array, mime: string): Uint8Array<ArrayBuffer> => new Uint8Array(mime.startsWith("image/") ? markAiImage(bytes) : bytes);

/**
 * A share card (next/og ImageResponse) with the mark written into its PNG: for a card that shows a generated portrait.
 * Its own headers are kept (cache-control above all), plus AI_HEADERS.
 */
export async function markedImageResponse(res: Response): Promise<Response> {
  const bytes = markAiImage(Buffer.from(await res.arrayBuffer()));
  const headers = new Headers(res.headers);
  headers.delete("content-length");
  for (const [k, v] of Object.entries(AI_HEADERS)) headers.set(k, v);
  return new Response(new Uint8Array(bytes), { status: res.status, headers });
}
