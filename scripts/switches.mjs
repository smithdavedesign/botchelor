#!/usr/bin/env node
/**
 * The switches inventory (docs/switches.md): every environment name the app's code reads, how a switch defaults, where
 * it's read and which docs explain it. Names only, never a value.
 *
 *   node scripts/switches.mjs          rewrite the generated half of docs/switches.md
 *   node scripts/switches.mjs --check  exit 1 when the page is out of date
 *
 * tests/switches-doc.test.ts fails when the code reads a name the page doesn't list, so a new switch gets a line.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url)).replace(/\/$/, "");
export const DOC = "docs/switches.md";
export const BEGIN = "<!-- BEGIN: generated by scripts/switches.mjs, do not edit by hand -->";
export const END = "<!-- END: generated -->";

// process.env.X, env.X (the env parameter most modules take), e.X, and process.env["X"].
const DOT = /(?:process\.env|\benv|\bENV|\be)\.([A-Z][A-Z0-9_]{2,})\b/g;
const BRACKET = /(?:process\.env|\benv|\bENV)\[\s*["'`]([A-Z][A-Z0-9_]{2,})["'`]\s*\]/g;
// A switch that is on unless "0", and one that is off unless "1".
const ON = /\.([A-Z][A-Z0-9_]{2,})\??(?:\.trim\(\))?\s*(?:!==?|===?)\s*"0"/g;
const OFF = /\.([A-Z][A-Z0-9_]{2,})\??(?:\.trim\(\))?\s*===?\s*"1"/g;

/** The app's own source: app/, lib/ and the root files Next.js loads, tests left out. */
function sourceFiles(root) {
  const out = [];
  for (const dir of ["app", "lib"]) {
    for (const f of readdirSync(join(root, dir), { recursive: true })) {
      const path = `${dir}/${String(f)}`;
      if (/\.(ts|tsx)$/.test(path) && !/\.test\.tsx?$/.test(path)) out.push(path);
    }
  }
  for (const f of ["middleware.ts", "instrumentation.ts", "next.config.ts"]) {
    try {
      readFileSync(join(root, f));
      out.push(f);
    } catch {
      /* not in this checkout */
    }
  }
  return out.sort();
}

function docFiles(root) {
  const out = readdirSync(root).filter((f) => f.endsWith(".md"));
  for (const f of readdirSync(join(root, "docs"), { recursive: true })) {
    const path = `docs/${String(f)}`;
    if (path.endsWith(".md") && path !== DOC) out.push(path);
  }
  return out.sort();
}

/**
 * Every name the code reads: { name, kind: "on" | "off" | "value", files, docs, spec }. kind is "on" when the code
 * compares it with "0" (on unless 0), "off" when with "1" (off unless 1), and "value" otherwise.
 */
export function scanSwitches(root = ROOT) {
  const names = new Map();
  const seen = (name) => {
    if (!names.has(name)) names.set(name, { name, on: false, off: false, files: new Set() });
    return names.get(name);
  };
  for (const file of sourceFiles(root)) {
    const text = readFileSync(join(root, file), "utf8");
    for (const re of [DOT, BRACKET]) for (const m of text.matchAll(re)) seen(m[1]).files.add(file);
    for (const m of text.matchAll(ON)) if (names.has(m[1])) names.get(m[1]).on = true;
    for (const m of text.matchAll(OFF)) if (names.has(m[1])) names.get(m[1]).off = true;
  }
  const docs = docFiles(root).map((f) => [f, readFileSync(join(root, f), "utf8")]);
  const specs = [".do/show.yaml", ".do/app.yaml"].map((f) => [f, readFileSync(join(root, f), "utf8")]);
  return [...names.values()]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((r) => {
      const word = new RegExp(`\\b${r.name}\\b`);
      return {
        name: r.name,
        kind: r.on && !r.off ? "on" : r.off && !r.on ? "off" : "value",
        files: [...r.files].sort(),
        docs: docs.filter(([, t]) => word.test(t)).map(([f]) => f),
        spec: specs.filter(([, t]) => word.test(t)).map(([f]) => f.replace(".do/", "")),
      };
    });
}

const list = (items, max) => (items.length > max ? `${items.slice(0, max).join(", ")} +${items.length - max}` : items.join(", "));
const row = (r) =>
  `| \`${r.name}\` | ${list(r.files.map((f) => `\`${f}\``), 1)} | ${r.spec.join(", ") || "-"} | ${r.docs.length ? list(r.docs, 2) : "**nowhere else**"} |`;

/** The generated half of the page: the counts, then a table for each kind. */
export function renderSwitches(rows) {
  const of = (kind) => rows.filter((r) => r.kind === kind);
  const head = "| Name | Read in | In the spec (`.do/`) | Also explained in |\n|---|---|---|---|";
  return [
    BEGIN,
    "",
    `${rows.length} names: ${of("on").length} switches on unless \`0\`, ${of("off").length} off unless \`1\`, and ${of("value").length} that take a value (keys, addresses, models, limits). ` +
      `${rows.filter((r) => !r.docs.length).length} are explained nowhere but here.`,
    "",
    "### On unless `0`",
    "",
    head,
    ...of("on").map(row),
    "",
    "### Off unless `1`",
    "",
    head,
    ...of("off").map(row),
    "",
    "### Values: keys, addresses, models and limits",
    "",
    head,
    ...of("value").map(row),
    "",
    END,
  ].join("\n");
}

/** The page with its generated half brought up to date. */
export function updatedDoc(root = ROOT) {
  const page = readFileSync(join(root, DOC), "utf8");
  const a = page.indexOf(BEGIN);
  const b = page.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${DOC} has lost its generated markers`);
  return page.slice(0, a) + renderSwitches(scanSwitches(root)) + page.slice(b + END.length);
}

if (process.argv[1] && relative(process.argv[1], fileURLToPath(import.meta.url)) === "") {
  const next = updatedDoc();
  const now = readFileSync(join(ROOT, DOC), "utf8");
  if (process.argv.includes("--check")) {
    if (next !== now) {
      console.error(`${DOC} is out of date: run node scripts/switches.mjs`);
      process.exit(1);
    }
    console.log(`${DOC} is up to date`);
  } else {
    writeFileSync(join(ROOT, DOC), next);
    console.log(next === now ? `${DOC} was already up to date` : `${DOC} rewritten`);
  }
}
